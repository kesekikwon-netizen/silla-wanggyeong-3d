/**
 * @file blender_exporter.js
 * @description Direct Exporter from the Gyeongju 3D Engine to:
 * 1. Blender 4.2.3 Native Python Scene Builder (`BLENDER_EEVEE_NEXT` / `CYCLES` + `NISHITA` Sky + `AgX` + `mathutils.bvhtree`)
 * 2. Wavefront OBJ (`exportGyeongjuWavefrontObj`)
 * 3. Archaeological Evaluation Markdown Report (`generateArchaeologicalMarkdownReport`)
 */

import { sampleGyeongjuElevation } from '../core/gyeongju_dem_terrain.js';
import { getGyeongjuArchaeologySites3D } from '../core/gyeongju_archaeology_db.js';

/**
 * Generate a standalone Blender 4.2.3 Python script (`.py`) that builds the full 3D Gyeongju
 * Terrain, Silla Royal Monuments (Hwangnyongsa 9-Story Pagoda, Hwangnamdaechong Double Tumulus,
 * Wolseong, Cheomseongdae), 500m/1,000m Archaeological Survey Buffers, and Virtual Trenches
 * using the exact Blender 4.2 subsystems identified in our REA MCP analysis.
 *
 * Can be executed headless via:
 *   `blender.exe --background --python gyeongju_blender42_scene.py`
 * or opened interactively in Blender 4.2!
 */
export function generateBlender42PythonScript(evaluationReport, options = {}) {
  const gridResolution = options.gridResolution ?? 48;
  const extentM = options.extentM ?? 4000;
  const halfM = extentM * 0.5;
  const centerX = evaluationReport?.location?.worldX ?? 0.0;
  const centerZ = evaluationReport?.location?.worldZ ?? 0.0;

  // Pre-sample a compact DEM height grid around the evaluation center for immediate self-contained generation
  const vertices = [];
  for (let rz = 0; rz <= gridResolution; rz++) {
    const wz = centerZ - halfM + (rz / gridResolution) * extentM;
    for (let rx = 0; rx <= gridResolution; rx++) {
      const wx = centerX - halfM + (rx / gridResolution) * extentM;
      const wy = sampleGyeongjuElevation(wx, wz);
      // Blender Z-Up right-handed coordinate mapping:
      // Blender X = +East (wx), Blender Y = +North (-wz), Blender Z = +Up (wy)
      vertices.push([Number(wx.toFixed(2)), Number((-wz).toFixed(2)), Number(wy.toFixed(2))]);
    }
  }

  const sites = getGyeongjuArchaeologySites3D().map((s) => ({
    id: s.id,
    name: s.name,
    category: s.category,
    archetype3D: s.archetype3D,
    bx: Number(s.worldX.toFixed(2)),
    by: Number((-s.worldZ).toFixed(2)),
    bz: Number(s.groundElevationM.toFixed(2)),
    radiusM: s.footprintRadiusM,
    heightM: s.reconstructedHeightM,
  }));

  const evalSummary = evaluationReport
    ? {
        surveyName: evaluationReport.surveyName,
        bx: Number(evaluationReport.location.worldX.toFixed(2)),
        by: Number((-evaluationReport.location.worldZ).toFixed(2)),
        bz: Number(evaluationReport.location.worldY.toFixed(2)),
        score: evaluationReport.assessmentSummary.archaeologicalPotentialScore,
        grade: evaluationReport.assessmentSummary.recommendedActionGrade,
      }
    : {
        surveyName: '경주 왕경 중심 기준점',
        bx: 0,
        by: 0,
        bz: 44.5,
        score: 95,
        grade: '정밀 발굴조사 및 시굴조사 필수',
      };

  return `# -*- coding: utf-8 -*-
"""
Gyeongju 3D Archaeological Terrain & Royal Capital Scene Builder for Blender 4.2.3 LTS
Generated by hgis-3d-engine (REA MCP Blender 4.2 Architecture Bridge)

Subsystems utilized (verified via REA MCP on blender-4.2.3-windows-x64.zip):
- Render Engine: BLENDER_EEVEE_NEXT (bf_draw.lib: eevee_hizbuffer.cc, eevee_ambient_occlusion.cc, eevee_raytrace.cc)
- Atmosphere: ShaderNodeTexSky 'NISHITA' (bf_intern_sky.lib: sky_nishita.cpp)
- Color Management: OpenColorIO 2.3 'AgX' (opencolorio_2_3.dll / AgX_Base_sRGB.cube)
- Spatial Acceleration: mathutils.bvhtree.BVHTree & mathutils.kdtree.KDTree (PyInit_mathutils_bvhtree / kdtree)
"""

import bpy
import math
from mathutils import Vector
from mathutils.bvhtree import BVHTree
from mathutils.kdtree import KDTree

GRID_RES = ${gridResolution}
TERRAIN_VERTS = ${JSON.stringify(vertices)}
GYEONGJU_SITES = ${JSON.stringify(sites, null, 2)}
EVAL_TARGET = ${JSON.stringify(evalSummary, null, 2)}

def setup_blender42_eevee_next_and_agx():
    scene = bpy.context.scene
    # Blender 4.2 EEVEE Next engine identifier
    scene.render.engine = 'BLENDER_EEVEE_NEXT'
    if hasattr(scene, 'eevee'):
        if hasattr(scene.eevee, 'use_raytracing'):
            scene.eevee.use_raytracing = True
        if hasattr(scene.eevee, 'use_shadows'):
            scene.eevee.use_shadows = True

    # OpenColorIO AgX Tone Mapping (4.2/datafiles/colormanagement/luts/AgX_Base_sRGB.cube)
    scene.view_settings.view_transform = 'AgX'
    scene.view_settings.look = 'AgX - Medium High Contrast'

    # Nishita Physical Sky (bf_intern_sky.lib: sky_nishita.cpp)
    world = bpy.data.worlds.get("Gyeongju_Nishita_Sky") or bpy.data.worlds.new("Gyeongju_Nishita_Sky")
    scene.world = world
    world.use_nodes = True
    nodes = world.node_tree.nodes
    links = world.node_tree.links
    nodes.clear()

    node_sky = nodes.new(type='ShaderNodeTexSky')
    node_sky.sky_type = 'NISHITA'
    node_sky.sun_elevation = math.radians(42.0)
    node_sky.sun_rotation = math.radians(135.0)
    node_sky.altitude = 45.0
    node_sky.air_density = 1.0
    node_sky.dust_density = 1.1
    node_sky.ozone_density = 1.0

    node_bg = nodes.new(type='ShaderNodeBackground')
    node_bg.inputs['Strength'].default_value = 1.0
    node_out = nodes.new(type='ShaderNodeOutputWorld')
    links.new(node_sky.outputs['Color'], node_bg.inputs['Color'])
    links.new(node_bg.outputs['Background'], node_out.inputs['Surface'])

def build_gyeongju_terrain_mesh():
    faces = []
    cols = GRID_RES + 1
    for rz in range(GRID_RES):
        for rx in range(GRID_RES):
            i00 = rz * cols + rx
            i10 = i00 + 1
            i01 = (rz + 1) * cols + rx
            i11 = i01 + 1
            faces.append((i00, i10, i11, i01))

    mesh = bpy.data.meshes.new("Gyeongju_DEM_Mesh")
    mesh.from_pydata(TERRAIN_VERTS, [], faces)
    mesh.update()
    for poly in mesh.polygons:
        poly.use_smooth = True

    obj = bpy.data.objects.new("Gyeongju_DEM_Terrain", mesh)
    bpy.context.collection.objects.link(obj)

    # Build C-level K-DOP BVHTree (PyInit_mathutils_bvhtree) for viewshed & raycast verification
    bvh = BVHTree.FromPolygons(TERRAIN_VERTS, faces)
    hit_loc, hit_norm, hit_idx, hit_dist = bvh.ray_cast(
        Vector((EVAL_TARGET['bx'], EVAL_TARGET['by'], 1000.0)),
        Vector((0.0, 0.0, -1.0))
    )
    print(f"[BVHTree Verification] Survey Target Ground Hit: {hit_loc}, Normal: {hit_norm}")
    return obj, bvh

def build_silla_heritage_and_kdtree():
    kd = KDTree(len(GYEONGJU_SITES))
    for i, s in enumerate(GYEONGJU_SITES):
        kd.insert(Vector((s['bx'], s['by'], s['bz'])), i)
    kd.balance()

    # Query 1,000m radius around evaluation point using BLI_kdtree_3d
    target_vec = Vector((EVAL_TARGET['bx'], EVAL_TARGET['by'], EVAL_TARGET['bz']))
    nearby = kd.find_range(target_vec, 1000.0)
    print(f"[KDTree 1000m Search] Found {len(nearby)} Gyeongju archaeological sites near {EVAL_TARGET['surveyName']}")

    col = bpy.data.collections.new("Gyeongju_Silla_Monuments")
    bpy.context.collection.children.link(col)

    for s in GYEONGJU_SITES:
        if s['archetype3D'] in ('tumulus_single', 'tumulus_double', 'tumulus_cluster'):
            bpy.ops.mesh.primitive_uv_sphere_add(
                segments=32, ring_count=16,
                radius=s['radiusM'],
                location=(s['bx'], s['by'], s['bz'])
            )
            mound = bpy.context.active_object
            mound.name = f"{s['id']}_{s['name']}"
            mound.scale = (1.0, 1.35 if s['archetype3D'] == 'tumulus_double' else 1.0, s['heightM'] / max(1.0, s['radiusM']))
            col.objects.link(mound)
            bpy.context.collection.objects.unlink(mound)
        else:
            bpy.ops.mesh.primitive_cylinder_add(
                vertices=8 if s['archetype3D'] == 'observatory_tower' else 4,
                radius=min(40.0, s['radiusM'] * 0.35),
                depth=s['heightM'],
                location=(s['bx'], s['by'], s['bz'] + s['heightM'] * 0.5)
            )
            mon = bpy.context.active_object
            mon.name = f"{s['id']}_{s['name']}"
            col.objects.link(mon)
            bpy.context.collection.objects.unlink(mon)

    # Create 500m and 1000m Archaeological Impact Buffer Rings
    for radius_m in (500.0, 1000.0):
        bpy.ops.curve.primitive_bezier_circle_add(
            radius=radius_m,
            location=(EVAL_TARGET['bx'], EVAL_TARGET['by'], EVAL_TARGET['bz'] + 2.0)
        )
        ring = bpy.context.active_object
        ring.name = f"Archaeo_Buffer_{int(radius_m)}m"
        ring.data.bevel_depth = 2.5

if __name__ == "__main__":
    bpy.ops.wm.read_factory_settings(use_empty=True)
    setup_blender42_eevee_next_and_agx()
    build_gyeongju_terrain_mesh()
    build_silla_heritage_and_kdtree()
    print("[hgis-3d-engine] Gyeongju 3D Archaeological Scene initialized successfully.")
`;
}

/**
 * Export a terrain quadtree chunk set + 3D buildings/monuments to Wavefront `.obj` string.
 */
export function exportGyeongjuWavefrontObj(terrainQuadtree, sites = []) {
  const lines = [
    '# Wavefront OBJ exported by hgis-3d-engine (Gyeongju 3D Archaeological Engine)',
    '# CRS: Local 3D Meters centered on Gyeongju Wolseong/Cheomseongdae (35.8347N, 129.2190E)',
    'o Gyeongju_Terrain_DEM',
  ];

  let vertexOffset = 1;
  for (const chunk of terrainQuadtree.leafChunks) {
    const pos = chunk.positions;
    const norm = chunk.normals;
    const uvs = chunk.uvs;
    const idx = chunk.indices;
    const vCount = pos.length / 3;

    lines.push(`g Terrain_${chunk.chunkId}`);
    for (let i = 0; i < vCount; i++) {
      lines.push(
        `v ${pos[i * 3].toFixed(2)} ${pos[i * 3 + 1].toFixed(2)} ${pos[i * 3 + 2].toFixed(2)}`
      );
    }
    for (let i = 0; i < vCount; i++) {
      lines.push(`vt ${uvs[i * 2].toFixed(4)} ${uvs[i * 2 + 1].toFixed(4)}`);
    }
    for (let i = 0; i < vCount; i++) {
      lines.push(
        `vn ${norm[i * 3].toFixed(4)} ${norm[i * 3 + 1].toFixed(4)} ${norm[i * 3 + 2].toFixed(4)}`
      );
    }
    for (let i = 0; i < idx.length; i += 3) {
      const a = idx[i] + vertexOffset;
      const b = idx[i + 1] + vertexOffset;
      const c = idx[i + 2] + vertexOffset;
      lines.push(`f ${a}/${a}/${a} ${b}/${b}/${b} ${c}/${c}/${c}`);
    }
    vertexOffset += vCount;
  }

  return lines.join('\n');
}

/**
 * Generate a structured Korean Archaeological Evaluation Report in Markdown format.
 */
export function generateArchaeologicalMarkdownReport(report) {
  const loc = report.location;
  const geo = report.geomorphology;
  const prox = report.proximityAnalysis;
  const bang = report.bangrijeEvaluation;
  const vs = report.viewshedAnalysis;
  const sum = report.assessmentSummary;

  const siteRows = [...prox.sitesWithin500m, ...prox.sites500to1000m]
    .map(
      (s, i) =>
        `| ${i + 1} | **${s.name}** | ${s.designation} | ${s.period} | **${s.distanceM}m** (${s.directionKo}, ${s.azimuthDeg}°) | ${s.zoneBand} | ${s.siteElevationM}m |`
    )
    .join('\n');

  const viewshedRows = vs.landmarks
    .map(
      (v) =>
        `| ${v.landmarkName} | ${v.visible ? '가시(Visible)' : '차폐(Occluded)'} | ${v.distanceM}m | ${v.elevationAngleDeg}° |`
    )
    .join('\n');

  const stratRows = report.virtualTrenches.predictedStratigraphy
    .map(
      (l) =>
        `| **${l.layerCode}** | ${l.nameKo} | GL -${l.depthRangeM[0]}m ~ -${l.depthRangeM[1]}m | ${l.expectedFinds} |`
    )
    .join('\n');

  return `# 경주 3D 지형·고고학 정밀 입지 및 매장유산 영향평가 보고서

- **조사구역명**: ${report.surveyName}
- **좌표**: WGS84 \`(${loc.lat}°N, ${loc.lon}°E)\` / EPSG:5187 \`(X: ${loc.epsg5187X}m, Y: ${loc.epsg5187Y}m)\`
- **분석 엔진**: \`hgis-3d-engine\` (Blender 4.2 REA PBVH + 3D KD-Tree + Nishita/EEVEE 지형 파이프라인)

---

## 1. 종합 판정 요약

| 평가 항목 | 결과 |
|---|---|
| **매장유산 포장 가능성 종합점수** | **${sum.archaeologicalPotentialScore} / 100점** (\`${sum.riskLevel}\`) |
| **보존 및 조사 조치 권고 등급** | **${sum.recommendedActionGrade}** |
| **신라 왕경 방리제(坊里制) 구획** | ${bang.bangSectorLabel} (최인접 고대 도로망 추정선 이격 **${bang.minRoadDistM}m**) |
| **지형·지모학 분류** | ${geo.landformNameKo} (해발 **${geo.elevationM}m**, 경사도 **${geo.slopeDeg}°**, 사면향 **${geo.aspectDeg}°**, TPI **${geo.tpi}**) |
| **인접 수계** | ${geo.nearestRiverName} (직선 이격거리 **${geo.nearestRiverDistM}m**) |

> **종합 고고학 소견**: ${sum.synthesisOpinion}

---

## 2. 반경 500m / 1,000m 이내 인접 유적 분포 (\`BLI_kdtree_3d_find_range\`)

- **500m 이내 (직접 영향권)**: **${prox.within500mCount}개소**
- **500m ~ 1,000m (간접 영향권)**: **${prox.within500to1000mCount}개소**

| 연번 | 유적명 | 지정구분 | 시대 | 이격거리 및 방위 | 영향권 구분 | 유적 해발 |
|---:|---|---|---|---|---|---:|
${siteRows || '| - | 반경 1,000m 이내 주요 국가지정 유적 없음 | - | - | - | - | - |'}

---

## 3. 3D 가시권(Viewshed) 및 왕경 경관 축선 분석 (\`PBVHTree.hasLineOfSight\`)

- **왕경 주요 거점 가시율**: **${vs.visibleCount} / ${vs.totalLandmarks}개소 가시**

| 왕경 핵심 거점 | 3D 시선 교차 판정 | 직선거리 | 앙각(Elevation Angle) |
|---|---|---:|---:|
${viewshedRows}

---

## 4. 가상 시굴 트렌치(\`T-1·T-2\`) 추정 토층(Stratigraphy) 및 문화층 심도

| 층위 | 토층 및 문화층 명칭 | 추정 심도 (GL 기준) | 예상 출토 유구 및 유물 |
|---|---|---|---|
${stratRows}
`;
}
